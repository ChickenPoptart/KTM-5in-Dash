#!/usr/bin/env python3
"""Turn a TrueType font into an anti-aliased VLW font as a C header.

LovyanGFX draws VLW fonts smoothly (each pixel's coverage is blended with
the background), which keeps large numbers sharp instead of scaling a small
bitmap font up into blocks.

    make_vlw_font.py FONT.ttf SIZE NAME CHARS OUT.h

CHARS is either the literal characters to include, or "ascii" for printable
ASCII followed by any extra characters (e.g. "ascii°"). Needs Pillow (pip install pillow).
"""

import struct
import sys

from PIL import ImageFont


def glyph_data(font, ch, ascent):
    """VLW metrics and an 8-bit coverage bitmap for one character."""
    advance = round(font.getlength(ch))
    x0, y0, x1, y1 = font.getbbox(ch)
    width, height = max(0, x1 - x0), max(0, y1 - y0)
    if width == 0 or height == 0:
        return (ord(ch), 0, 0, advance, 0, 0), b""
    mask = font.getmask(ch, mode="L")
    mw, mh = mask.size
    bitmap = bytearray(width * height)
    for y in range(min(height, mh)):
        for x in range(min(width, mw)):
            bitmap[y * width + x] = mask.getpixel((x, y))
    # VLW: top extent is measured up from the baseline, which Pillow puts
    # at y = ascent
    return (ord(ch), height, width, advance, ascent - y0, x0), bytes(bitmap)


def build(ttf, size, chars):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    glyphs = [glyph_data(font, ch, ascent) for ch in sorted(set(chars))]
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for metrics, _ in glyphs:
        out += struct.pack(">7i", *metrics, 0)
    for _, bitmap in glyphs:
        out += bitmap
    return out


LICENSE_NOTE = "Rajdhani: SIL Open Font License 1.1 (see src/fonts/OFL.txt)."


def main():
    global LICENSE_NOTE
    ttf, size, name, chars, out_path = sys.argv[1:6]
    if "DSEG" in ttf:
        LICENSE_NOTE = "DSEG: SIL Open Font License 1.1 (see src/fonts/DSEG-LICENSE.txt)."
    if chars.startswith("ascii"):
        chars = "".join(chr(c) for c in range(32, 127)) + chars[5:]
    data = build(ttf, int(size), chars)
    lines = [
        f"// Generated by tools/make_vlw_font.py from {ttf.split('/')[-1]} at {size}px.",
        f"// {LICENSE_NOTE}",
        "#pragma once",
        "#include <stdint.h>",
        f"static const uint8_t {name}[] = {{",
    ]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_path}: {len(data)} bytes, {len(set(chars))} glyphs")


if __name__ == "__main__":
    main()
